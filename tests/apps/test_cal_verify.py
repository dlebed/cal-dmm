class ScriptedInput:
    """``builtins.input`` with a fixed script.  Records every prompt shown."""

    def __init__(self, answers=()):
        self.answers = list(answers)
        self.prompts = []

    def __call__(self, prompt=""):
        self.prompts.append(prompt)
        if not self.answers:
            return ""
        return self.answers.pop(0)


class NoInput:
    """``builtins.input`` that fails the test if the runner blocks on it."""

    def __call__(self, prompt=""):
        raise AssertionError(f"the runner prompted when it must not: {prompt!r}")


@pytest.fixture
def bench(monkeypatch):
    """Fake adapters, a fake probe factory, and no signal handler.

    ``StaticEnvironment`` is replaced so a test can stand in an ambient
    probe of its own (``fixture.probe``) when no ``--ambient`` is passed.
    """
    fixture = Bench()
    monkeypatch.setattr(cal_verify, "open_source", fixture.open_source)
    monkeypatch.setattr(cal_verify, "open_meter", fixture.open_meter)
    monkeypatch.setattr(cal_verify, "StaticEnvironment",
                        lambda ambient_c=None, **kwargs: (
                            fixture.probe
                            if ambient_c is None and fixture.probe is not None
                            else FakeProbe(ambient_c=ambient_c,
                                           source=kwargs.get("source",
                                                             "operator"))))
    # The real signal handler is asserted separately; leaving one installed
    # would outlive the test and take over pytest's own Ctrl-C.
    monkeypatch.setattr(cal_verify, "setup_graceful_shutdown",
                        fixture.shutdown_cleanups.append)
    return fixture


def invoke(argv, *, answers=None, monkeypatch=None, clock_step_s=1.0):
    """Run the CLI as it would really be run.  Returns the exit status.

    ``sys.argv`` is set from *argv* because the resume command the runner prints
    is rebuilt from it -- that is the point of the resume line, and a test that
    left pytest's own argv in place would assert nothing about it.
    """
    parser = cal_verify.build_parser()
    args = parser.parse_args(argv)
    if monkeypatch is not None:
        monkeypatch.setattr(sys, "argv", ["caldmm-cal-verify", *argv])
        monkeypatch.setattr("builtins.input",
                            ScriptedInput(answers) if answers is not None
                            else NoInput())
    return cal_verify.run(args, sleep=lambda seconds: None,
                          clock=FakeClock(clock_step_s))


def cli(csv_path, *, meter="hp3458a", quantities="DCV", extra=()):
    """The common argument vector: one calibrator, one meter, a small plan.

    ``--accept-max 1000`` is here because a dc-volts plan at 100 % reaches the
    1000 V range, and L87's rule is that ``--yes`` may not accept a hazardous
    output on nobody's behalf: unattended, the maximum has to be *stated*.
    It changes nothing for the interactive tests, which answer the typed
    confirmation themselves.
    """
    return ["--source", "fluke5700a:cal1:4",
            "--meter", f"{meter}:dmm1:22",
            "--dut", "meter",
            "--quantities", quantities,
            "--percentages", "100",
            "--no-negative",
            "--points", "ladder",
            "--acal-recent",
            "--accept-max", "1000",
            "-o", str(csv_path), *extra]


