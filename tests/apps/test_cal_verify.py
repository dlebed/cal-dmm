class FakeSource:
    """A :class:`~caldmm.cal.roles.SourceRole` that sources what it is asked."""

    def __init__(self, model_id="fluke5700a", *, health=HEALTHY,
                 offset_ppm=0.0, uncertainty=UNCERT_5PPM, device=None,
                 cal_temp_c=None):
        self.spec = load_model(model_id)
        self.model_id = self.spec.model_id
        self.device = device if device is not None else FakeCalibratorDevice()
        self.offset_ppm = float(offset_ppm)
        self.uncertainty = uncertainty
        self.cal_temp_c = cal_temp_c
        self._healths = list(health) if isinstance(health, list) else [health]
        self.health_calls = 0
        self.standby_calls = 0
        #: Every point that reached the terminals.  Empty means no output was
        #: ever commanded, which is what a declined confirmation has to prove.
        self.applied = []

    def cal_temperature(self):
        """The optional capability the runner reads for the header."""
        return self.cal_temp_c

    def validate(self, point):
        return []

    def apply(self, point):
        self._refuse_beyond_entry_limits(point)
        self.applied.append(point)
        value = float(point.value)
        return SourceState(
            actual_value=value * (1.0 + self.offset_ppm * 1e-6),
            unit=Quantity(point.quantity).unit,
            frequency_hz=float(getattr(point, "frequency_hz", 0.0) or 0.0),
            range_id=getattr(point, "range_id", None),
            uncertainty=self.uncertainty,
            settled=True, operate=True)

    def _refuse_beyond_entry_limits(self, point):
        """Model ``LIMIT``, on a device that carries one (faults 815/856).

        Every **entry** the real adapter makes reaches the interlock, not just
        the setpoint: a point that needs ``RANGELCK`` is programmed to the
        range-lock *anchor* first ([SM 2007] 3-16, ``_source_on_locked_range``)
        and an anchor above the armed limit faults exactly as a setpoint would.
        A device with no ``check_entry`` is the calibrator nobody armed.
        """
        check = getattr(self.device, "check_entry", None)
        if check is None:
            return
        unit = Quantity(point.quantity).unit
        function = self.spec.function(Quantity(point.quantity))
        range_id = getattr(point, "range_id", None)
        if function is not None and range_id:
            range_spec = next((r for r in function.ranges
                               if r.range_id == range_id), None)
            if range_spec is not None and needs_range_lock(
                    function, range_spec, float(point.value)):
                anchor = range_lock_anchor(
                    function, range_spec,
                    frequency_hz=float(getattr(point, "frequency_hz", 0.0)
                                       or 0.0))
                if anchor is not None:
                    check(anchor, unit)
        check(float(point.value), unit)

    def standby(self):
        self.standby_calls += 1

    def health(self):
        index = min(self.health_calls, len(self._healths) - 1)
        self.health_calls += 1
        return self._healths[index]


class FakeMeter:
    """A :class:`~caldmm.cal.roles.MeterRole` that reads what it was set to."""

    def __init__(self, model_id="hp3458a", *, error=0.0, spread=1e-9,
                 device=None, on_read=None, fail_at=None,
                 internal_temp_c=None):
        self.spec = load_model(model_id)
        self.model_id = self.spec.model_id
        self.device = device if device is not None else FakeMeterDevice()
        self.error = float(error)
        self.spread = float(spread)
        self.on_read = on_read
        self.internal_temp_c = internal_temp_c
        self._fail_at = fail_at
        self.configured = []
        #: Plan points configured so far -- **not** counting the engine's
        #: safe-level wiring proofs (Global Constraints §8), which are not
        #: points of the plan.  ``on_read``/``fail_at`` hooks are keyed on
        #: this, because they mean "the Nth point of the run".
        self.points = 0
        self._proof = False
        self._config = None
        self._value = None
        self._quantity = None
        #: The bench's source, set by ``Bench.open_meter``; ``None`` reads
        #: the configured value, as a meter used on its own does here.
        self.linked_source = None

    def _prestep_pending(self, last) -> bool:
        """The source is at a tenth of what the meter was ranged for."""
        if self._value is None or not self._value:
            return False
        return math.isclose(float(last.value), self._value * 0.1,
                            rel_tol=1e-9)

    def internal_temperature(self):
        """The optional capability the engine records per point."""
        return self.internal_temp_c

    def range_readback(self):
        """``<func>:RANGe?`` / ``RANGE?`` -- what three of the four adapters do.

        Modelled because §9's pre-step depends on it: a meter whose range
        cannot be **read back** now gets the 10 %-of-target pre-step above
        22 V, exactly as one that cannot fix its range at all (the 1281's
        case), and a fake without the capability would put pre-steps into
        these runs that a real 3458A or 34401A does not have.
        """
        return None if self._config is None else self._config.range_fs

    def supports(self, quantity, connection=Connection.TWO_WIRE):
        function = self.spec.function(Quantity(quantity))
        if function is None:
            return False
        return (not function.connections
                or Connection(connection) in function.connections)

    def configure(self, point):
        self.configured.append(point)
        self._proof = str(getattr(point, "label", "")).startswith(
            "wiring proof")
        if not self._proof:
            self.points += 1
        quantity = Quantity(point.quantity)
        function = self.spec.function(quantity)
        range_arg = getattr(point, "range_arg", None)
        range_spec = None
        if range_arg is not None:
            for candidate in function.ranges:
                arg = (candidate.range_arg if candidate.range_arg is not None
                       else candidate.fs)
                if math.isclose(arg, float(range_arg), rel_tol=1e-9):
                    range_spec = candidate
                    break
        if range_spec is None:
            range_spec = select_range(function, abs(float(point.value)))
        if range_spec is None:
            raise RuntimeError(f"no range holds {point.value}")
        self._value = float(point.value)
        self._quantity = quantity
        self._config = MeterConfig(
            func=function.func, range_arg=range_arg, range_fs=range_spec.fs,
            nplc=100.0, mode=getattr(point, "mode", None),
            resolution=range_spec.resolution, settle_s=0.0,
            applied={"nplc": 100.0})
        return self._config

    def read(self, n, *, discard=0):
        if not self._proof:
            if self.on_read is not None:
                self.on_read(self.points)
            if self._fail_at is not None:
                self._fail_at(self.points)
        base = self._value
        applied = getattr(self.linked_source, "applied", None)
        if applied and self._prestep_pending(applied[-1]):
            base = float(applied[-1].value)
        base += self.error
        # The spread is a volts/ohms figure; a current point's tolerance on
        # the 100 nA range is 40 pA, so the same 1 nA would be a gross error.
        spread = (self.spread * 1e-6
                  if self._quantity in (Quantity.DCI, Quantity.ACI)
                  else self.spread)
        samples = [base + (spread if i % 2 == 0 else -spread)
                   for i in range(n)]
        return Reading.from_samples(
            samples, overload=self.spec.is_overload, discarded=discard,
            resolution=self._config.resolution,
            unit=self._quantity.unit if self._quantity else "")


class FakeProbe:
    """An :class:`~caldmm.cal.roles.EnvironmentProbe` with a fixed answer."""

    def __init__(self, ambient_c=23.0, *, humidity_pct=45.0, source="probe",
                 error=None):
        self.ambient_c = ambient_c
        self.humidity_pct = humidity_pct
        self.source = source
        self.error = error
        self.calls = 0

    def read(self):
        self.calls += 1
        if self.error is not None:
            raise self.error
        return Environment(ambient_c=self.ambient_c,
                           humidity_pct=self.humidity_pct,
                           timestamp=datetime(2026, 1, 1, tzinfo=timezone.utc),
                           source=self.source)


class FakeClock:
    """A monotonic clock that never sleeps."""

    def __init__(self, step_s=1.0):
        self.now = datetime(2026, 8, 1, 12, 0, tzinfo=timezone.utc)
        self.step = timedelta(seconds=step_s)

    def __call__(self):
        self.now = self.now + self.step
        return self.now


class Bench:
    """The instruments the runner will find when it opens them."""

    def __init__(self, source=None, meter=None, probe=None):
        self.source = source if source is not None else FakeSource()
        self.meter = meter if meter is not None else FakeMeter()
        self.probe = probe
        self.opened = []
        self.shutdown_cleanups = []

    # -- the two adapter factories the runner calls
    def open_source(self, model_id, instrument, **kwargs):
        self.opened.append(("source", model_id, instrument))
        return self.source

    def open_meter(self, model_id, instrument, **kwargs):
        self.opened.append(("meter", model_id, instrument))
        # Wired to the source, so a 10 %-of-target pre-step (any current
        # above 220 mA, engine section 9) reads the tenth that was sourced
        # rather than the full value the meter was ranged for.
        if getattr(self.meter, "linked_source", False) is None:
            self.meter.linked_source = self.source
        return self.meter


