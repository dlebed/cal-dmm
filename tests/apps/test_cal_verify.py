class PostRecordingSource(FakeSource):
    """A source that answers the CUR_POST pair Task 8 put on the adapter.

    ``reports`` is what ``CUR_POST?`` comes back with, so a unit that ignores
    the write -- the case the read-back exists for -- can be described.
    """

    def __init__(self, *args, post="NORMAL", reports=None, **kwargs):
        super().__init__(*args, **kwargs)
        self.post = str(post)
        self.reports = reports
        self.post_calls = []

    def current_post(self):
        return self.reports or self.post

    def set_current_post(self, post):
        self.post_calls.append(str(post).upper())
        if self.reports is not None and self.reports != str(post).upper():
            from caldmm.cal.adapters import AdapterError
            raise AdapterError(
                f"asked for CUR_POST {post}, the calibrator reports "
                f"{self.reports}")
        self.post = str(post).upper()
        return self.post


