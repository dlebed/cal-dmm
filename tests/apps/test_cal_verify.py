# combinations it refuses, that the record reaches disk on every path, and that
# it branches on ``complete``/``committed`` and never on ``failed``.

def _utc():
    return datetime.now(timezone.utc)


class StubAdjust(HP3458AExternalAdjust):
    """The real ``finalize`` and the real runner, one controllable step.

    Subclasses the 3458A procedure so ``finalize`` -- the thing the record is
    built from -- is the real implementation, and overrides everything that
    would need an instrument or a certificate.
    """

    def __init__(self, *, problems=(), on_prepare=None, on_step=None,
                 nvram=None):
        self.problems = list(problems)
        self.on_prepare = on_prepare
        self.on_step = on_step
        self.nvram = nvram

    def precheck(self, ctx):
        return list(self.problems)

    def preflight(self, ctx):
        return list(self.problems)

    def prepare(self, ctx):
        if self.on_prepare is not None:
            self.on_prepare(ctx)

    def steps(self, ctx):
        def action(c, step):
            if self.on_step is not None:
                self.on_step(c, step)
            return StepResult(step_id=step.id, outcome=StepOutcome.EXECUTED,
                              started_at=_utc(), finished_at=_utc(),
                              writes_nvram=True, commands=step.commands,
                              nvram=self.nvram,
                              response="stub adjustment stored")

        yield AdjustStep(id="write", prompt="connect the standard",
                         action=action, writes_nvram=True,
                         commands=("CAL 10.0001",),
                         confirm="writing calibration memory")


