class CalAwareMeter(FakeMeter):
    """A 3458A fake that knows its adjustment temperatures and runs ACAL."""

    def __init__(self, *, now_c=23.0, cal_c=23.0, **kwargs):
        super().__init__("hp3458a", **kwargs)
        self.now_c, self.cal_c = now_c, cal_c
        self.autocals = []

    def internal_temperature(self):
        return self.now_c

    def cal_temperatures(self):
        return {"cal0": self.cal_c, "dcv": self.cal_c, "ohms": self.cal_c}

    def autocal(self, kind="ALL"):
        self.autocals.append(kind)


class TestFullVerification:
    def test_the_manufacturer_point_set_is_two_groups(self, tmp_path, bench,
                                                      monkeypatch, capsys):
        status = invoke(["--source", "fluke5700a:4", "--meter", "hp3458a:22",
                         "--points", "manufacturer", "--dry-run",
                         "-o", str(tmp_path / "run.csv")],
                        monkeypatch=monkeypatch)
        out = capsys.readouterr().out
        assert status == cal_verify.EXIT_OK
        assert "42 points in 2 wiring groups" in out
        assert "group 1/2  voltage/ohms terminals" in out
        assert "group 2/2  current terminals" in out

    def test_the_full_plan_is_two_groups(self, tmp_path, bench, monkeypatch,
                                         capsys):
        invoke(["--source", "fluke5700a:4", "--meter", "hp3458a:22",
                "--dry-run", "-o", str(tmp_path / "run.csv")],
               monkeypatch=monkeypatch)
        out = capsys.readouterr().out
        assert "in 2 wiring groups" in out
        for segment in ("DCV 2w", "ACV 2w", "RES 4w", "RES 2w", "DCI 2w",
                        "ACI 2w"):
            assert segment in out, segment

    def test_the_current_prompt_says_which_lead_to_move(self):
        plan = generate_plan("fluke5700a", "hp3458a", dut_role="meter",
                             quantities=["DCI", "ACI"], percentages=(100.0,),
                             include_negative=False, point_set="ladder")
        (group,) = plan.groups()
        boundary = cal_verify.GroupBoundary(index=0, total=1, group=group,
                                            start=0)
        text = "\n".join(cal_verify.wiring_instructions(
            boundary, current_post="NORMAL"))
        assert "current terminals" in text
        assert "to its current (I) input" in text
        assert "DCI 2w" in text and "ACI 2w" in text

    def test_acal_runs_unattended_before_the_first_point(self, tmp_path, bench,
                                                         monkeypatch, capsys):
        bench.meter = CalAwareMeter()
        sleeps = []
        path = tmp_path / "run.csv"
        monkeypatch.setattr(sys, "argv", ["caldmm-cal-verify"])
        monkeypatch.setattr("builtins.input", ScriptedInput(["y", "yes", ""]))
        args = cal_verify.build_parser().parse_args(
            cli(path, extra=["--ambient", "23.0", "--acal"]))
        status = cal_verify.run(args, sleep=sleeps.append, clock=FakeClock())
        assert status in (cal_verify.EXIT_OK, cal_verify.EXIT_FAIL)
        assert bench.meter.autocals == ["ALL"]
        assert bench.source.standby_calls >= 1
        assert sum(sleeps) >= 30 * 60
        header, _rows = load_results(str(path))
        assert header.extra["acal"] == "ALL"
        assert header.extra["meter_cal59_temp_c"] == "23.00"

    def test_a_meter_far_from_its_adjustment_temperature_is_refused(
            self, tmp_path, bench, monkeypatch, capsys):
        bench.meter = CalAwareMeter(now_c=31.0, cal_c=23.0)
        status = invoke(cli(tmp_path / "run.csv", extra=["--ambient", "23.0"]),
                        answers=["y", "yes", ""], monkeypatch=monkeypatch)
        err = capsys.readouterr().err
        assert status == cal_verify.EXIT_USAGE
        assert "8.0 C from CAL? 59" in err
        assert bench.source.applied == []

    def test_force_runs_it_but_states_no_conformity(self, tmp_path, bench,
                                                    monkeypatch, capsys):
        """Outside Tcal +/- 5 C the data sheet's figures are not in force, so
        ``--force`` buys measurements, never a PASS or a FAIL."""
        bench.meter = CalAwareMeter(now_c=31.0, cal_c=23.0)
        path = tmp_path / "run.csv"
        status = invoke(cli(path, extra=["--ambient", "23.0", "--force"]),
                        answers=["y", "yes", ""], monkeypatch=monkeypatch)
        assert status in (cal_verify.EXIT_OK, cal_verify.EXIT_FAIL)
        header, rows = load_results(str(path))
        assert rows
        assert all(cal_verify.FLAG_METER_OUTSIDE_TCAL in row.flags
                   for row in rows)
        assert {row.verdict for row in rows} == {Verdict.INDETERMINATE}
        assert "CAL? 59 8.00 C" in header.extra["meter_outside_tcal"]


