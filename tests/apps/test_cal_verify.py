"""Tests for caldmm.apps.cal_verify -- the verification runner.

**Fake roles, real everything else.**  No hardware, no database, no signals and
no sleeping.  What the fakes replace is exactly the two adapters and the
environment probe; the plan is generated by the real
:func:`caldmm.cal.plan.generate_plan` from the real specification files, the
rows are produced by the real :func:`caldmm.cal.engine.run_plan`, and the file
is written and read back by the real :mod:`caldmm.cal.result`.

That is deliberate.  A fixture that hands the runner a hand-built plan and
hand-built rows can describe a world the system cannot produce -- and a defect
that survives review is usually one whose test fixture was more permissive than
the code.  Every value here comes out of a real constructor:
:class:`~caldmm.cal.roles.SourceState`, :class:`~caldmm.cal.roles.SourceHealth`,
:meth:`~caldmm.cal.roles.Reading.from_samples`,
:class:`~caldmm.cal.roles.MeterConfig`, and
:func:`caldmm.drivers.fluke5700a.parse_idn` for the identity string.
"""

