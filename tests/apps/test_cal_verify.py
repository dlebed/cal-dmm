def _interrupt_at(point_number):
    """A meter that raises KeyboardInterrupt on the Nth configured point.

    KeyboardInterrupt is a BaseException, so the engine's per-point ``except
    Exception`` does not swallow it -- it unwinds through the generator exactly
    as a real Ctrl-C during a reading does, running the ``finally`` that puts
    the source in standby.
    """
    def hook(configured):
        if configured == point_number:
            raise KeyboardInterrupt
    return hook


