class TestPointIdentity:
    """The plan side and the row side of a resume must agree exactly."""

    @staticmethod
    def _plan():
        return generate_plan("fluke5700a", "hp3458a", dut_role="meter",
                             quantities=["DCV"], percentages=(100.0,),
                             include_negative=False)

    @staticmethod
    def _row(point):
        """The row this point would become -- through ``from_measurement``.

        Not a hand-built ``ResultRow``: the mapping from a plan point's fields
        onto a row's is exactly what these two key functions have to agree
        about, and a fixture that set the fields itself would be asserting its
        own assumption instead of the code's.
        """
        budget = UncertaintyBudget()
        return ResultRow.from_measurement(
            point=point, conformity=evaluate(0.0, None, budget), budget=budget)

    def test_plan_point_and_its_own_row_have_the_same_key(self):
        for point in self._plan().points:
            assert point_key(self._row(point)) == \
                cal_verify.plan_point_key(point)

    def test_a_different_setpoint_is_a_different_point(self):
        plan = self._plan()
        first, second = plan.points[0], plan.points[-1]
        assert cal_verify.plan_point_key(first) != \
            cal_verify.plan_point_key(second)

    def test_the_same_setpoint_on_two_ranges_is_two_points(self):
        """The aliasing that broke ``compare_runs``.

        A meter-DUT plan pins the meter's range with ``range_arg`` and carries
        no ``range_id`` at all, so a key without the range collapses all five
        ``DCV 0 V`` points of this plan into one.
        """
        zeros = [p for p in self._plan().points if p.value == 0.0]
        assert len(zeros) == 5, "one zero per dc range"
        assert len({cal_verify.plan_point_key(p) for p in zeros}) == 5
        assert len({point_key(self._row(p)) for p in zeros}) == 5


class TestResumePoint:
    """Where a resumed run starts -- group *and* offset within it."""

    @staticmethod
    def _plan():
        # Two wiring groups: dc volts on the voltage/ohms terminals, then dc
        # current on the current terminals.
        return generate_plan("fluke5700a", "hp3458a", dut_role="meter",
                             quantities=["DCV", "DCI"], percentages=(100.0,),
                             include_negative=False, point_set="ladder")

    @staticmethod
    def _rows(plan, indices):
        """Rows for the given **plan indices**, in any order, with repeats.

        Taking indices rather than a count is what lets a fixture describe a
        file with a group measured twice -- the state that a count-based
        `resume_group` read as "complete" while the group's tail had never been
        taken.  A fixture that could not build it is why that survived review.
        """
        groups = plan.groups()
        rows = []
        for index in indices:
            point = plan.points[index]
            group = next(number for number, g in enumerate(groups)
                         if g.start <= index < g.start + len(g))
            rows.append(ResultRow(quantity=point.quantity,
                                  nominal=point.value,
                                  point_index=index, group_index=group))
        return rows

    def test_an_empty_file_starts_at_the_beginning(self):
        assert cal_verify.resume_point(self._plan(), []) == (0, 0)

    def test_a_complete_group_is_not_repeated(self):
        plan = self._plan()
        first = len(plan.groups()[0])
        rows = self._rows(plan, range(first))
        assert cal_verify.resume_point(plan, rows) == (1, 0)

    def test_a_partial_group_is_continued_where_it_stopped(self):
        plan = self._plan()
        first = len(plan.groups()[0])
        rows = self._rows(plan, range(first + 3))
        assert cal_verify.resume_point(plan, rows) == (1, 3)

    def test_a_group_measured_twice_is_not_mistaken_for_a_finished_one(self):
        """The regression: counting rows, not points, loses a group's tail.

        A group restarted after an interrupt has rows for some of its points
        twice.  Counting rows reaches `len(group)` while the last points were
        never measured, and the run reports itself complete with a row count
        that matches the plan exactly -- nothing downstream can tell.
        """
        plan = self._plan()
        first = len(plan.groups()[0])
        second = len(plan.groups()[1])
        # Group 1 attempted twice: 2 points, then all but 2 from the start.
        indices = (list(range(first))
                   + [first, first + 1]
                   + list(range(first, first + second - 2)))
        rows = self._rows(plan, indices)
        assert len(rows) == first + second, \
            "the file has as many rows as the plan has points"
        assert cal_verify.resume_point(plan, rows) == (1, second - 2)

    def test_a_finished_run_has_nothing_left(self):
        plan = self._plan()
        rows = self._rows(plan, range(len(plan.points)))
        assert cal_verify.resume_point(plan, rows) == (len(plan.groups()), 0)

    def test_a_proof_row_does_not_count_as_its_point_measured(self):
        """2026-11-01 DCI: a run stopped at the wiring proof before point 27.

        The proof row carries point 27's index.  Counting it as measured
        resumes at 28 and silently never takes point 27.
        """
        plan = self._plan()
        rows = self._rows(plan, range(5))
        proof = rows[-1]
        rows.append(replace(proof, point_index=5,
                            label="wiring proof (source range change) "
                                  "before DCV 10 V"))
        assert cal_verify.resume_point(plan, rows) == (0, 5)

    def test_a_proof_row_is_not_a_plan_mismatch(self):
        plan = self._plan()
        rows = self._rows(plan, range(5))
        rows.append(replace(rows[-1], point_index=5,
                            label="wiring proof (run start) before x"))
        assert not any(cal_verify.is_proof_row(row) for row in rows[:5])
        assert cal_verify.is_proof_row(rows[5])


