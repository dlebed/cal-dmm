def _plan_topping_out_at(tmp_path, maximum_v, name="capped"):
    """Save a DCV plan whose largest setpoint is exactly *maximum_v*.

    Source-DUT, because 22.000 V is only a real setpoint from that side: the
    5700A's DC22V range makes it the 100 %-of-range point, while no 3458A range
    puts a setpoint anywhere near the 22 V line.  The plan comes out of the real
    generator and is then *filtered*, so every point in it is one the shipped
    plan also contains -- a hand-built 22 V point would prove only that the
    fixture can describe 22 V.
    """
    from caldmm.cal.plan import save_plan

    plan = generate_plan("fluke5700a", "hp3458a", dut_role="source",
                         quantities=["DCV"], percentages=(90.0, 100.0),
                         include_negative=False, name=name)
    kept = tuple(point for point in plan.points
                 if abs(float(point.value)) <= maximum_v)
    capped = replace(plan, points=kept)
    assert max(abs(float(p.value)) for p in kept) == maximum_v
    assert validate_plan(capped, "fluke5700a", "hp3458a") == []
    path = tmp_path / f"{name}.yaml"
    save_plan(capped, str(path))
    return path


